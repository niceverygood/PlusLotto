// Extract only the reset contract from postgres-meta generated output; never author DB columns here.
import fs from 'node:fs'
import ts from 'typescript'

const [input, output] = process.argv.slice(2)
if (!input || !output) throw new Error('Usage: node scripts/extract-member-reset-types.mjs generated-full.ts output.ts')
const source = ts.createSourceFile(input, fs.readFileSync(input, 'utf8'), ts.ScriptTarget.Latest, true)
const aliases = source.statements.filter(ts.isTypeAliasDeclaration)
const json = aliases.find(node => node.name.text === 'Json')
const database = aliases.find(node => node.name.text === 'Database')
const named = (members, name) => members.find(node => node.name?.getText(source).replaceAll('"', '') === name)
const publicSchema = named(database?.type.members ?? [], 'public')
if (!json || !database || !publicSchema || !ts.isTypeLiteralNode(publicSchema.type)) throw new Error('Unexpected generator output')
const keep = { Tables: ['member_reco_reset_archive', 'member_reset_receipts'], Functions: ['admin_reset_members'] }
const sections = Object.entries(keep).map(([key, names]) => {
  const section = named(publicSchema.type.members, key)
  if (!section || !ts.isTypeLiteralNode(section.type)) throw new Error(`Missing generated section ${key}`)
  const members = names.map(name => named(section.type.members, name))
  if (members.some(member => !member)) throw new Error(`Missing generated contract in ${key}`)
  return ts.factory.updatePropertySignature(section, section.modifiers, section.name, section.questionToken,
    ts.factory.updateTypeLiteralNode(section.type, members))
})
const schema = ts.factory.updatePropertySignature(publicSchema, publicSchema.modifiers, publicSchema.name,
  publicSchema.questionToken, ts.factory.updateTypeLiteralNode(publicSchema.type, sections))
const contract = ts.factory.updateTypeAliasDeclaration(database, database.modifiers, database.name,
  database.typeParameters, ts.factory.updateTypeLiteralNode(database.type, [schema]))
const printer = ts.createPrinter({ newLine: ts.NewLineKind.LineFeed })
fs.writeFileSync(output, '// Generated by postgres-meta v0.99.0 from the reset migration applied to isolated PostgreSQL 17.\n' +
  '// Reduced by scripts/extract-member-reset-types.mjs; do not edit DB shapes by hand.\n' +
  [json, contract].map(node => printer.printNode(ts.EmitHint.Unspecified, node, source)).join('\n') + '\n')
